#!/usr/bin/env node
// Generates src/generated/finance-shapes.ts from specs/finance.yaml: per-route
// request shapes (allowed + required fields) and response shapes (fields the
// success envelope's result actually carries). The mock transport uses these to
// reject invented request fields and to stop echoing request-only fields into
// responses. Runs as part of `npm run generate`; the output is committed.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const spec = parse(readFileSync(new URL("../specs/finance.yaml", import.meta.url), "utf8"));

function deref(node) {
  if (node && typeof node === "object" && node.$ref) {
    const parts = node.$ref.replace(/^#\//, "").split("/");
    let cur = spec;
    for (const p of parts) cur = cur?.[p];
    return deref(cur);
  }
  return node;
}

function schemaProps(schema) {
  schema = deref(schema);
  if (!schema) return undefined;
  if (schema.allOf) {
    const merged = { properties: {}, required: [] };
    for (const part of schema.allOf.map(deref)) {
      Object.assign(merged.properties, part.properties ?? {});
      merged.required.push(...(part.required ?? []));
    }
    return merged;
  }
  return schema;
}

function requestShape(schema) {
  const s = schemaProps(schema);
  if (!s?.properties) return undefined;
  const properties = {};
  for (const [key, prop] of Object.entries(s.properties)) {
    const resolved = schemaProps(prop);
    properties[key] =
      resolved?.type === "object" && resolved.properties
        ? Object.keys(resolved.properties)
        : null;
  }
  return { required: s.required ?? [], properties };
}

function responseFields(responses) {
  for (const code of ["200", "201", "202"]) {
    const content = responses?.[code]?.content?.["application/json"]?.schema;
    if (!content) continue;
    const envelope = schemaProps(content);
    let result = envelope?.properties?.result;
    if (!result) continue;
    result = schemaProps(result);
    if (result?.type === "array") result = schemaProps(result.items);
    if (result?.properties) return Object.keys(result.properties);
  }
  return undefined;
}

const requestShapes = {};
const responseShapes = {};
for (const [path, ops] of Object.entries(spec.paths ?? {})) {
  for (const method of ["post", "put", "patch"]) {
    const op = ops[method];
    if (!op) continue;
    const key = `${method.toUpperCase()} ${path}`;
    const body = op.requestBody?.content?.["application/json"]?.schema;
    const req = body ? requestShape(body) : undefined;
    if (req) requestShapes[key] = req;
    const res = responseFields(op.responses);
    if (res) responseShapes[key] = res;
  }
}

const banner = `// GENERATED by scripts/generate-mock-shapes.mjs from specs/finance.yaml.
// Do not edit by hand; run \`npm run generate\`.

/** Allowed and required request-body fields per mutating route. Nested arrays
 * list the allowed keys of one-level object properties; null = scalar/array. */
export interface RequestShape {
  required: string[];
  properties: Record<string, string[] | null>;
}
`;

writeFileSync(
  new URL("../src/generated/finance-shapes.ts", import.meta.url),
  banner +
    `\nexport const financeRequestShapes: Record<string, RequestShape> = ${JSON.stringify(requestShapes, null, 2)};\n` +
    `\n/** Fields the success envelope's result schema actually declares, per route. */\nexport const financeResponseShapes: Record<string, string[]> = ${JSON.stringify(responseShapes, null, 2)};\n`,
);
console.log(
  `finance-shapes.ts: ${Object.keys(requestShapes).length} request shapes, ${Object.keys(responseShapes).length} response shapes`,
);
